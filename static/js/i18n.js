const LANG_KEY = 'callejon9_lang';

/** Traduce un key al idioma actual. Útil en JS inline: t('login_btn') */
function t(key) {
  const lang = localStorage.getItem(LANG_KEY) || 'es';
  return (I18N[lang] && I18N[lang][key] != null) ? I18N[lang][key] : (I18N.es[key] || key);
}

/** Aplica todas las traducciones al DOM. */
function i18nApply(lang) {
  const dict = I18N[lang] || I18N.es;

  // [data-i18n] → textContent
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = dict[el.dataset.i18n];
    if (v != null) el.textContent = v;
  });

  // [data-i18n-placeholder] → placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = dict[el.dataset.i18nPlaceholder];
    if (v != null) el.placeholder = v;
  });

  // Nav links por href (no requiere atributos extra en cada template)
  document.querySelectorAll('a.nav-link').forEach(a => {
    const key = HREF_KEYS[a.getAttribute('href')];
    if (!key) return;
    // el último <span> contiene el label (el primero puede ser el ícono)
    const spans = a.querySelectorAll('span');
    const label = spans[spans.length - 1];
    if (label && !label.hasAttribute('data-i18n')) label.textContent = dict[key] || label.textContent;
  });

  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
  _syncBtns(lang);
}

/** Alterna entre ES y EN. */
function i18nToggle() {
  const current = localStorage.getItem(LANG_KEY) || 'es';
  i18nApply(current === 'es' ? 'en' : 'es');
}

function _syncBtns(lang) {
  document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
    const esEl = btn.querySelector('[data-lang-es]');
    const enEl = btn.querySelector('[data-lang-en]');
    if (esEl) { esEl.style.fontWeight = lang === 'es' ? '700' : '400'; esEl.style.opacity = lang === 'es' ? '1' : '0.42'; }
    if (enEl) { enEl.style.fontWeight = lang === 'en' ? '700' : '400'; enEl.style.opacity = lang === 'en' ? '1' : '0.42'; }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  i18nApply(localStorage.getItem(LANG_KEY) || 'es');
});
